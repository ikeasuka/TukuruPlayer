// Builds the web runtime that is embedded in the iOS app.
// Output: ../ios/TukuruPlayer/WebRuntime (folder reference in the Xcode project)
import * as esbuild from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = process.env.TKR_OUT || path.join(here, "..", "ios", "TukuruPlayer", "WebRuntime");
fs.mkdirSync(out, { recursive: true });

// Collect Ruby sources (RGSS implementation) into a generated module.
const rbDir = path.join(here, "rgss");
const rbFiles = fs.readdirSync(rbDir).filter((f) => f.endsWith(".rb")).sort();
const sources = {};
for (const f of rbFiles) sources[f] = fs.readFileSync(path.join(rbDir, f), "utf8");
fs.writeFileSync(
  path.join(here, "src", "rgss_sources.gen.js"),
  "// Generated by build.mjs - do not edit\nexport default " + JSON.stringify(sources) + ";\n"
);

// Build identifier (git commit) so logs show exactly which runtime is running.
let buildId = "dev";
try {
  const { execSync } = await import("node:child_process");
  buildId = execSync("git rev-parse --short HEAD", { cwd: here }).toString().trim();
} catch (e) { /* not a git checkout */ }

await esbuild.build({
  define: { __TKR_BUILD__: JSON.stringify(buildId + " " + new Date().toISOString().slice(0, 16)) },
  entryPoints: [path.join(here, "src", "main.js")],
  bundle: true,
  format: "iife",
  target: ["safari16"],
  outfile: path.join(out, "app.js"),
  minify: process.env.TKR_MINIFY !== "0",
  sourcemap: false,
  logLevel: "info",
});

fs.copyFileSync(path.join(here, "src", "index.html"), path.join(out, "index.html"));
const wasmSrc = path.join(here, "node_modules", "@ruby", "3.4-wasm-wasi", "dist", "ruby.wasm");
const wasmDst = path.join(out, "ruby.wasm");
if (!fs.existsSync(wasmDst) || fs.statSync(wasmDst).size !== fs.statSync(wasmSrc).size) {
  fs.copyFileSync(wasmSrc, wasmDst);
}
console.log("Web runtime written to", out);
